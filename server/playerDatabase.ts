// Dynamic age computation
export function computeAge(birthDate?: string, isRetired?: boolean, now: Date = new Date()): string | undefined {
  if (!birthDate || birthDate.trim() === '' || birthDate === 'غير متاح') return undefined;

  let birthYear: number | undefined;
  let birthMonth: number | undefined; // 0-indexed
  let birthDay: number | undefined;

  const isoMatch = birthDate.match(/(\d{4})[-/](\d{1,2})[-/](\d{1,2})/);
  if (isoMatch) {
    birthYear = parseInt(isoMatch[1], 10);
    birthMonth = parseInt(isoMatch[2], 10) - 1;
    birthDay = parseInt(isoMatch[3], 10);
  } else {
    const arabicMatch = birthDate.match(/(\d{1,2})\s+([^\s\d(),]+)\s+(\d{4})/);
    if (arabicMatch) {
      birthDay = parseInt(arabicMatch[1], 10);
      const monthStr = arabicMatch[2].replace(/[أإآٱ]/g, 'ا').replace(/[ىئ]/g, 'ي').trim();
      const AR_MONTHS: Record<string, number> = {
        يناير: 0,
        فبراير: 1,
        مارس: 2,
        ابريل: 3,
        مايو: 4,
        يونيو: 5,
        يوليو: 6,
        اغسطس: 7,
        سبتمبر: 8,
        اكتوبر: 9,
        نوفمبر: 10,
        ديسمبر: 11
      };
      birthMonth = AR_MONTHS[monthStr];
      birthYear = parseInt(arabicMatch[3], 10);
    } else {
      const yearOnlyMatch = birthDate.match(/\b(19\d{2}|20\d{2})\b/);
      if (yearOnlyMatch) {
        birthYear = parseInt(yearOnlyMatch[1], 10);
      }
    }
  }

  if (!birthYear || isNaN(birthYear)) return undefined;

  let age = now.getFullYear() - birthYear;
  const isApproximate = birthMonth === undefined || birthDay === undefined;

  if (birthMonth !== undefined && birthDay !== undefined) {
    const mDiff = now.getMonth() - birthMonth;
    if (mDiff < 0 || (mDiff === 0 && now.getDate() < birthDay)) {
      age--;
    }
  }

  if (age < 10 || age > 120) return undefined;

  const prefix = isApproximate ? 'حوالي ' : '';
  return isRetired ? `${prefix}${age} سنة (معتزل)` : `${prefix}${age} سنة`;
}

// Self-test for computeAge on startup
export function selfTestComputeAge(): boolean {
  try {
    const test1 = computeAge('1990-01-01', false, new Date('2025-01-02'));
    const test2 = computeAge('15 يونيو 1992', false, new Date('2025-06-14'));
    const test3 = computeAge('15 يونيو 1992', true, new Date('2025-06-16'));

    const pass = test1 === '35 سنة' && test2 === '32 سنة' && test3 === '33 سنة (معتزل)';
    if (!pass) {
      console.warn('⚠️ [computeAge] Self-test failed:', { test1, test2, test3 });
      return false;
    }
    return true;
  } catch (err) {
    console.warn('⚠️ [computeAge] Self-test exception:', err);
    return false;
  }
}

// Validate database integrity and duplicates
export function validateDatabase(): string[] {
  const warnings: string[] = [];
  const seenIds = new Set<string>();
  const seenDisplayNames = new Set<string>();
  const aliasToPlayer = new Map<string, string>();

  const allowedSharedAliases = new Set(
    ['رونالدو', 'ronaldo', 'سيلفا', 'توريس', 'ديمبيلي', 'سواريز', 'مارتينيز', 'ميندي', 'زيزو', 'المايسترو', 'القديس'].map(
      (a) => normalizeSearch(a)
    )
  );

  for (const player of FAMOUS_PLAYERS_DB) {
    if (!player.id) warnings.push(`لاعب بدون ID: ${player.displayName || player.name}`);
    if (seenIds.has(player.id)) warnings.push(`معرف مكرر: ${player.id}`);
    seenIds.add(player.id);

    if (!player.name) warnings.push(`لاعب بدون اسم إنجليزي: ${player.id}`);
    if (!player.displayName) warnings.push(`لاعب بدون اسم عربي: ${player.id}`);
    if (seenDisplayNames.has(player.displayName)) warnings.push(`اسم عربي مكرر: ${player.displayName}`);
    seenDisplayNames.add(player.displayName);

    if (!player.nationality) warnings.push(`لاعب بدون جنسية: ${player.id}`);
    if (!player.position) warnings.push(`لاعب بدون مركز: ${player.id}`);
    if (!player.clubs || player.clubs.length === 0) warnings.push(`لاعب بدون أندية: ${player.id}`);

    if (player.aliases) {
      for (const alias of player.aliases) {
        const normA = normalizeSearch(alias);
        if (!normA) continue;
        if (aliasToPlayer.has(normA)) {
          const existingPlayerId = aliasToPlayer.get(normA)!;
          if (existingPlayerId !== player.id && !allowedSharedAliases.has(normA)) {
            warnings.push(`لقب مشترك مش في القائمة المسموحة: "${alias}" بين ${existingPlayerId} و ${player.id}`);
          }
        } else {
          aliasToPlayer.set(normA, player.id);
        }
      }
    }
  }

  // Validate PLAYERS_INDEX
  for (const player of PLAYERS_INDEX) {
    if (!player.id) warnings.push(`لاعب فهرس بدون ID: ${player.displayName || player.name}`);
    if (!player.id.startsWith('idx-')) warnings.push(`معرف فهرس لا يبدأ بـ idx-: ${player.id}`);
    if (seenIds.has(player.id)) warnings.push(`معرف مكرر في الفهرس: ${player.id}`);
    seenIds.add(player.id);

    if (!player.name) warnings.push(`لاعب فهرس بدون اسم إنجليزي: ${player.id}`);
    if (!player.displayName) warnings.push(`لاعب فهرس بدون اسم عربي: ${player.id}`);
    if (seenDisplayNames.has(player.displayName)) warnings.push(`اسم عربي مكرر بين الفهرس والقاعدة: ${player.displayName}`);
    seenDisplayNames.add(player.displayName);

    if (!player.nationality) warnings.push(`لاعب فهرس بدون جنسية: ${player.id}`);
    if (!player.position) warnings.push(`لاعب فهرس بدون مركز: ${player.id}`);
  }

  if (warnings.length > 0) {
    console.warn(`⚠️ [validateDatabase] Warnings found (${warnings.length}):`, warnings);
  }
  return warnings;
}

// Helper: Strip Arabic definite article "ال"
export function stripAl(term: string): string {
  return term
    .split(' ')
    .map((w) => (w.startsWith('ال') && w.length > 3 ? w.slice(2) : w))
    .join(' ');
}

// Helper: Normalize string for fuzzy matching (Arabic & English)
export function normalizeSearch(str: string): string {
  if (!str) return '';
  return str
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '') // remove Latin diacritics (é -> e, etc.)
    .toLowerCase()
    .trim()
    .replace(/[أإآٱ]/g, 'ا')
    .replace(/[ىئ]/g, 'ي')
    .replace(/ؤ/g, 'و')
    .replace(/ة/g, 'ه')
    .replace(/[\u064B-\u065F\u0640]/g, '') // remove arabic diacritics & tatweel
    .replace(/[-_.,;!?()/\\]+/g, ' ')
    .replace(/\s+/g, ' ');
}

// Bounded Levenshtein distance: if distance exceeds max, returns max + 1
export function editDistance(a: string, b: string, max: number): number {
  if (a === b) return 0;
  const la = a.length;
  const lb = b.length;
  if (Math.abs(la - lb) > max) return max + 1;
  if (la === 0) return lb <= max ? lb : max + 1;
  if (lb === 0) return la <= max ? la : max + 1;

  let s1 = a;
  let s2 = b;
  if (s1.length > s2.length) {
    s1 = b;
    s2 = a;
  }

  const n = s1.length;
  const m = s2.length;
  const prevRow = new Array<number>(n + 1);
  const currRow = new Array<number>(n + 1);

  for (let i = 0; i <= n; i++) {
    prevRow[i] = i;
  }

  for (let j = 1; j <= m; j++) {
    currRow[0] = j;
    let minInRow = currRow[0];

    for (let i = 1; i <= n; i++) {
      const cost = s1[i - 1] === s2[j - 1] ? 0 : 1;
      const val = Math.min(
        currRow[i - 1] + 1,
        prevRow[i] + 1,
        prevRow[i - 1] + cost
      );
      currRow[i] = val;
      if (val < minInRow) {
        minInRow = val;
      }
    }

    if (minInRow > max) {
      return max + 1;
    }

    for (let i = 0; i <= n; i++) {
      prevRow[i] = currRow[i];
    }
  }

  return prevRow[n] <= max ? prevRow[n] : max + 1;
}

// Fuzzy search across candidate pool
export function searchFuzzy<T extends { id: string; name: string; displayName: string; aliases: string[] }>(
  query: string,
  pool: T[]
): T[] {
  const normQuery = stripAl(normalizeSearch(query)).trim();
  if (normQuery.length < 4) return [];

  const maxDist = normQuery.length <= 7 ? 1 : 2;
  const isSingleWord = !normQuery.includes(' ');

  const matches: { item: T; dist: number }[] = [];

  for (const item of pool) {
    let bestDist = maxDist + 1;

    const candidates: string[] = [];
    if (item.displayName) {
      const normDN = stripAl(normalizeSearch(item.displayName)).trim();
      if (normDN) candidates.push(normDN);
    }
    if (item.name) {
      const normN = stripAl(normalizeSearch(item.name)).trim();
      if (normN) candidates.push(normN);
    }
    if (item.aliases) {
      for (const al of item.aliases) {
        const normAl = stripAl(normalizeSearch(al)).trim();
        if (normAl) candidates.push(normAl);
      }
    }

    for (const cand of candidates) {
      const d = editDistance(normQuery, cand, maxDist);
      if (d < bestDist) {
        bestDist = d;
      }
      if (bestDist === 0) break;

      if (isSingleWord) {
        const words = cand.split(/\s+/).filter((w) => w.length >= 4);
        for (const w of words) {
          const wd = editDistance(normQuery, w, maxDist);
          if (wd < bestDist) {
            bestDist = wd;
          }
          if (bestDist === 0) break;
        }
      }
    }

    if (bestDist <= maxDist) {
      matches.push({ item, dist: bestDist });
    }
  }

  matches.sort((a, b) => {
    if (a.dist !== b.dist) return a.dist - b.dist;
    return (a.item.displayName || a.item.name).localeCompare(b.item.displayName || b.item.name, 'ar');
  });

  return matches.slice(0, 4).map((m) => m.item);
}

// Find matching players in the built-in database with intelligent cross-script canonical ranking
export function searchBuiltinPlayers(query: string): StoredPlayer[] {
  const normQuery = normalizeSearch(query);
  if (normQuery.length < 2) return [];
  const queryNoAl = stripAl(normQuery);
  const queryCanon = buildCanonicalNameKey(query);

  const results: { player: StoredPlayer; score: number }[] = [];

  for (const player of FAMOUS_PLAYERS_DB) {
    let score = 0;
    const normDisplayName = normalizeSearch(player.displayName);
    const normDisplayNameNoAl = stripAl(normDisplayName);
    const normName = normalizeSearch(player.name);
    const normId = normalizeSearch(player.id);
    const dnCanon = buildCanonicalNameKey(player.displayName);
    const enCanon = buildCanonicalNameKey(player.name);

    // Exact match on display name, official name, or canonical cross-script identity
    if (normDisplayName === normQuery || normName === normQuery || normId === normQuery) {
      score += 100;
    } else if (normDisplayNameNoAl === queryNoAl) {
      score += 98;
    } else if (
      queryCanon.canonicalKey &&
      (dnCanon.canonicalKey === queryCanon.canonicalKey ||
        enCanon.canonicalKey === queryCanon.canonicalKey)
    ) {
      score += 96;
    } else if (normQuery.length >= 3) {
      if (queryCanon.tokenKeys.length <= 1) {
        if (normDisplayName.includes(normQuery) || normName.includes(normQuery)) {
          score += 70;
        } else if (normDisplayNameNoAl.includes(queryNoAl)) {
          score += 65;
        } else if (
          queryCanon.tokenKeys.length === 1 &&
          (dnCanon.tokenKeys.includes(queryCanon.tokenKeys[0]) ||
            enCanon.tokenKeys.includes(queryCanon.tokenKeys[0]))
        ) {
          score += 65;
        }
      } else {
        if (normDisplayName.includes(normQuery) || normName.includes(normQuery)) {
          score += 70;
        } else if (normDisplayNameNoAl.includes(queryNoAl)) {
          score += 65;
        } else if (
          queryCanon.tokenKeys.every(
            (tk) => dnCanon.tokenKeys.includes(tk) || enCanon.tokenKeys.includes(tk)
          )
        ) {
          score += 65;
        }
      }
    }

    // Check aliases
    for (const alias of player.aliases) {
      const normAlias = normalizeSearch(alias);
      const normAliasNoAl = stripAl(normAlias);
      const aliasCanon = buildCanonicalNameKey(alias);

      if (
        normAlias === normQuery ||
        normAliasNoAl === queryNoAl ||
        (queryCanon.canonicalKey && aliasCanon.canonicalKey === queryCanon.canonicalKey)
      ) {
        score += 95;
        break;
      } else if (normQuery.length >= 3 && normAlias.length >= 3) {
        if (queryCanon.tokenKeys.length <= 1) {
          if (normAlias.includes(normQuery) || normQuery.includes(normAlias)) {
            score += 55;
            break;
          }
        } else if (
          normAlias.includes(normQuery) ||
          queryCanon.tokenKeys.every((tk) => aliasCanon.tokenKeys.includes(tk))
        ) {
          score += 55;
          break;
        }
      }
    }

    // Only consider secondary attributes (clubs/nationality) if there is already a name link
    if (score >= 50 && normQuery.length >= 3) {
      if (normalizeSearch(player.nationality).includes(normQuery)) {
        score += 10;
      }
      if (player.clubs.some((c) => normalizeSearch(c).includes(normQuery))) {
        score += 10;
      }
    }

    if (score >= 50) {
      results.push({ player, score });
    }
  }

  results.sort((a, b) => b.score - a.score);
  return results.map((r) => r.player);
}

// Get player by ID or exact / canonical match
export function getBuiltinPlayerByIdOrName(nameOrId: string): StoredPlayer | undefined {
  if (!nameOrId) return undefined;
  const norm = normalizeSearch(nameOrId);
  const normNoAl = stripAl(norm);
  const queryCanon = buildCanonicalNameKey(nameOrId);

  return FAMOUS_PLAYERS_DB.find((p) => {
    if (
      p.id === nameOrId ||
      normalizeSearch(p.id) === norm ||
      normalizeSearch(p.displayName) === norm ||
      stripAl(normalizeSearch(p.displayName)) === normNoAl ||
      normalizeSearch(p.name) === norm
    ) {
      return true;
    }
    if (queryCanon.canonicalKey) {
      if (
        buildCanonicalNameKey(p.displayName).canonicalKey === queryCanon.canonicalKey ||
        buildCanonicalNameKey(p.name).canonicalKey === queryCanon.canonicalKey
      ) {
        return true;
      }
    }
    return p.aliases.some((a) => {
      const normA = normalizeSearch(a);
      return (
        normA === norm ||
        stripAl(normA) === normNoAl ||
        (queryCanon.canonicalKey && buildCanonicalNameKey(a).canonicalKey === queryCanon.canonicalKey)
      );
    });
  });
}

// Generate smart offline assistant response using profile facts
export function generateLocalAssistantReply(profile: any, question: string): string {
  const normQ = normalizeSearch(question);
  const name = profile.displayName || profile.playerName || 'اللاعب';
  const isConfidentNegative = profile.researchMode === 'local_db' && !profile.isCustomOrSecret;

  if (normQ.includes('اسبانيا') || normQ.includes('ريال') || normQ.includes('برشلونة') || normQ.includes('مدريد')) {
    const hasSpain =
      profile.clubs?.some((c: string) => /ريال|برشلونة|إسبان|اسبان|مدريد|أتلتيكو/i.test(c)) ||
      profile.leagues?.some((l: string) => /إسبان|اسبان|ليجا/i.test(l));
    if (hasSpain) return `أيوه، ${name} لعب في إسبانيا بالفعل مع أندية هناك.`;
    if (isConfidentNegative) return `لأ، ${name} ملعبش في الدوري الإسباني أو للأندية دي.`;
    return `مش مسجل عندي في الملف إنه لعب في إسبانيا، بس تأكد من معلوماتك.`;
  }

  if (normQ.includes('ايطاليا') || normQ.includes('يوفنتوس') || normQ.includes('ميلان') || normQ.includes('انتر') || normQ.includes('روما')) {
    const hasItaly =
      profile.clubs?.some((c: string) => /يوفنتوس|ميلان|إنتر|انتر|روما|فيورنتينا|نابولي|إيطال|ايطال/i.test(c)) ||
      profile.leagues?.some((l: string) => /إيطال|ايطال|كالتشيو/i.test(l));
    if (hasItaly) return `أيوه، ${name} لعب في الدوري الإيطالي (الكالتشيو).`;
    if (isConfidentNegative) return `لأ، ${name} ملعبش في إيطاليا.`;
    return `مش مسجل عندي في الملف إنه لعب في إيطاليا، بس تأكد من معلوماتك.`;
  }

  if (
    normQ.includes('انجلترا') ||
    normQ.includes('ليفربول') ||
    normQ.includes('يونايتد') ||
    normQ.includes('سيتي') ||
    normQ.includes('تشيلسي') ||
    normQ.includes('ارسنال') ||
    normQ.includes('بريميرليج') ||
    normQ.includes('استون فيلا')
  ) {
    const hasEngland =
      profile.clubs?.some((c: string) => /ليفربول|مانشستر|تشيلسي|أرسنال|ارسنال|سيتي|توتنهام|إنجلترا|استون|أستون/i.test(c)) ||
      profile.leagues?.some((l: string) => /إنجليز|انجليز|بريميرليج/i.test(l));
    if (hasEngland) return `أيوه، ${name} لعب في الدوري الإنجليزي الممتاز (البريميرليج).`;
    if (isConfidentNegative) return `لأ، ${name} ملعبش في إنجلترا.`;
    return `مش مسجل عندي في الملف إنه لعب في إنجلترا، بس تأكد من معلوماتك.`;
  }

  if (normQ.includes('دوري الابطال') || normQ.includes('ابطال اوروبا') || normQ.includes('تشامبيونز')) {
    const hasUCL =
      profile.trophies?.some((t: string) => /دوري أبطال|دوري ابطال|أبطال أوروبا|ابطال اوروبا/i.test(t)) ||
      profile.internationalTrophies?.some((c: string) => /دوري أبطال|دوري ابطال|أبطال أوروبا/i.test(c));
    if (hasUCL) return `أيوه، ${name} شارك وتوج بلقب دوري أبطال أوروبا في مسيرته.`;
    if (isConfidentNegative) return `لأ، ${name} متوجش بلقب دوري أبطال أوروبا (مش مسجل في مسيرته).`;
    return `مش مسجل في الملف إنه فاز بدوري الأبطال، راجع معلوماتك.`;
  }

  if (normQ.includes('كاس العالم') || normQ.includes('مونديال')) {
    const hasWC =
      profile.internationalTournaments?.some((c: string) => /كأس العالم|مونديال/i.test(c)) ||
      profile.internationalTrophies?.some((t: string) => /كأس العالم|بطل العالم/i.test(t)) ||
      profile.trophies?.some((t: string) => /كأس العالم|بطل العالم/i.test(t));
    if (hasWC) return `أيوه، ${name} شارك في بطولة كأس العالم مع منتخبه الوطني.`;
    if (isConfidentNegative) return `لأ، مشاركش أو متوجش بكأس العالم.`;
    return `مش مسجل في الملف مشاركته في كأس العالم، راجع معلوماتك.`;
  }

  if (normQ.includes('معتزل') || normQ.includes('بيلعب دلوقتي') || normQ.includes('حالي')) {
    if (profile.isRetired) return `أيوه، ${name} معتزل كرة القدم حالياً.`;
    return `لأ، ${name} لاعب نشط وبيلعب حالياً في نادي ${profile.currentClub || 'محترف'}.`;
  }

  if (normQ.includes('مهاجم') || normQ.includes('مركز') || normQ.includes('دفاع') || normQ.includes('وسط') || normQ.includes('حارس') || normQ.includes('جناح')) {
    if (profile.position) return `مركز ${name} الأساسي هو: ${profile.position}.`;
  }

  if (normQ.includes('جنسية') || normQ.includes('بلد') || normQ.includes('منتخب')) {
    if (profile.nationality || profile.nationalTeam) {
      return `${name} بيمثل منتخب ${profile.nationality || profile.nationalTeam}.`;
    }
  }

  if (normQ.includes('اهلي') || normQ.includes('الأهلي')) {
    const hasAhly = profile.clubs?.some((c: string) => /الأهلي|الاهلي/i.test(c));
    if (hasAhly) return `أيوه، ${name} لعب للنادي الأهلي المصري.`;
    if (isConfidentNegative) return `لأ، ${name} ملعبش للنادي الأهلي.`;
    return `مش مسجل في الملف إنه لعب للأهلي.`;
  }

  if (normQ.includes('زمالك') || normQ.includes('الزمالك')) {
    const hasZamalek = profile.clubs?.some((c: string) => /الزمالك/i.test(c));
    if (hasZamalek) return `أيوه، ${name} لعب لنادي الزمالك المصري.`;
    if (isConfidentNegative) return `لأ، ${name} ملعبش لنادي الزمالك.`;
    return `مش مسجل في الملف إنه لعب للزمالك.`;
  }

  return 'مش لاقي إجابة مباشرة للسؤال ده في الملف، جاوب من معلوماتك.';
}
